import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import {readEraArchive} from '../resources.mjs';
import {parseCreatureExperience} from '../creatures/crexpbon.mjs';
import {simulateSourceXpCache14} from '../creatures/source-xp-cache14.mjs';

// Resolve the COMPLETE cache before selecting scalar rows. Filtering the input
// would free occupied slots and incorrectly admit rows the original drops.
const project=path.resolve(process.argv[2]||'.');
const source=path.resolve(process.argv[3]||'../Third-Upgrade-Mod-Full');
const archive=readEraArchive(fs.readFileSync(path.join(source,'Data/AmeCre.pac')));
assert.equal(archive.sha256,'452c833214b4c6df2a5e430bf4dd526ccd71792ede166ac2d77646516322731c');
const raw=archive.extract('crexpbon.txt');
const rows=parseCreatureExperience(raw.toString('latin1'));
const levelSource=fs.readFileSync(path.join(project,'work/vcmi-wasm/lib/era/EraSourceCreatureLevels.h'),'utf8');
const levels=levelSource.match(/sourceInitialCreatureLevels\{\{([^}]+)\}\}/)[1].split(',').map(Number);
const ids=[...new Set([...levelSource.matchAll(/\{"[^"\n]+",(\d+)\}/g)].map(m=>Number(m[1])))].filter(id=>levels[id]>=0&&levels[id]<=7).sort((a,b)=>a-b);
const selected=[];
for(const id of ids){
 assert(levels[id]>=0&&levels[id]<=7);
 const cache=simulateSourceXpCache14(rows,{sourceId:id,zeroBasedLevel:levels[id]});
 for(const [slot,row]of cache.table.entries())if(row&&'ADHMSmRbL'.includes(row.code))
 {
  if(row.code==='b')assert.equal(row.modifier,'='.charCodeAt(0),'Fractional reduction requires a separate carrier');
  if(row.code==='R')assert.equal(row.modifier,'+'.charCodeAt(0),'Nonadditive retaliation needs explicit per-round replacement');
  selected.push({id,slot,...row});
 }
}
const modifiers=archive.extract('crexpmod.txt').toString('latin1').split(/\r?\n/).slice(1).filter(s=>/^-?\d+\t/.test(s)).map(s=>{
 const c=s.split('\t');return{id:Number(c[0]),multiplier:Math.trunc(Number(c[1])*1000),rank10:Number(c[3]),cap:Number(c[4]),rank11:Number(c[5])};
});
const progression=ids.map(id=>{
 const row=modifiers.find(r=>r.id===id)||modifiers.find(r=>r.id===-(Math.min(levels[id],6)+1));
 assert(row);return {id,...row,id};
});
const text=`/* Generated by import-henchmen-banner-table.mjs. Dormant until native admission.
 * AmeCre.pac SHA256 ${archive.sha256}
 * crexpbon.txt SHA256 ${crypto.createHash('sha256').update(raw).digest('hex')}
 * Full original14-slot resolution precedes ADHMSm/R/b/L selection.
 */
#pragma once
#include "EraHenchmanRules.h"
#include <array>
namespace era_bridge::henchmen {
struct SourceBannerRow {int sourceId,slot;char code;unsigned char modifier;std::array<unsigned char,11> values;};
inline constexpr std::array<SourceBannerRow,${selected.length}> sourceBannerRows{{
${selected.map(r=>` {${r.id},${r.slot},'${r.code}',${r.modifier},{{${r.chances.join(',')}}}}`).join(',\n')}
}};
struct SourceHenchmanExperience {int sourceId;StackExperienceTable table;};
inline constexpr std::array<SourceHenchmanExperience,${progression.length}> sourceHenchmanExperience{{
${progression.map(r=>` {${r.id},{${r.rank10},${r.rank11},${r.cap},${r.multiplier}}}`).join(',\n')}
}};
inline const StackExperienceTable * sourceExperienceTable(int sourceId) {
 for(const auto & row:sourceHenchmanExperience)if(row.sourceId==sourceId)return &row.table;
 return nullptr;
}
}
`;
fs.writeFileSync(path.join(project,'work/vcmi-wasm/lib/era/EraHenchmanBannerSourceRows.h'),text);
console.log(JSON.stringify({actors:ids.length,rows:selected.length}));
