import assert from 'node:assert/strict';
import fs from 'node:fs';

export async function runFrozenModule({boot,state,command,readCompletedNativeSave,page,report}){
 for(const enabled of [true,false]){
  await boot({enabled});assert.equal(!!(await state()).mithrilEnabled,enabled);
  const save=await readCompletedNativeSave(page(),command,{tag:enabled?921:922});await page().close();
  await boot({save:[...save],enabled:!enabled});assert.equal(!!(await state()).mithrilEnabled,enabled);
  report.scenarios.push(enabled?'mithril-enabled-choice-survives-save-with-disabled-installation-default':'mithril-disabled-choice-survives-save-with-enabled-installation-default');await page().close();
 }
}

export async function runLegacySites({boot,panel,nextDay,state,command,wait,page,report}){
 assert(process.env.MITHRIL_LEGACY_SAVE,'Provide the save generated by the old test engine');
 await boot({save:[...fs.readFileSync(process.env.MITHRIL_LEGACY_SAVE)],enabled:false,henchmen:true});
 assert.equal((await state()).mithrilEnabled,true,'The saved setting wins over current installation defaults');
 let data=await panel();assert.equal(data.amount,76);
 const gold=data.offers.find(row=>row.kind===0&&row.x===12&&row.y===11);assert(gold?.active);assert.equal(gold.days,7);assert.equal(gold.dailyIncome,2000);
 assert(data.offers.some(row=>row.kind===2&&row.active));assert(data.offers.some(row=>row.kind===3&&row.active));
 assert(!data.offers.some(row=>row.kind===1&&row.x===12&&row.y===12&&row.cost===1));assert(!data.offers.some(row=>row.kind===7));
 await page().locator('[data-mithril-close]').tap();await command(55);await wait(()=>goonkMobileState.heroWindow?.henchman?.unit);
 assert.equal((await state()).heroWindow.henchman.unit.key,'core:archangel');assert((await state()).heroWindow.henchman.alive);
 await command(63);await wait(()=>goonkMobileState.mode==='map');
 for(let day=2;day<=8;++day){await nextDay();data=await panel();const mine=data.offers.find(row=>row.id===gold.id);assert.equal((await state()).day,day);assert.equal(mine.active,day<8);assert.equal(mine.days,Math.max(0,8-day));assert.equal(mine.dailyIncome,day<8?2000:1000);assert.equal(data.amount,76);}
 report.scenarios.push('old-engine-save-retains-mithril-settings-improvements-wallet-and-companion');
 report.scenarios.push('old-engine-save-mine-duration-continues-and-expires-without-extension');
 await page().close();
}
